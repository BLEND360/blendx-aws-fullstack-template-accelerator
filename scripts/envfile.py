"""Read and update KEY=value lines in a .env file, so deploy scripts configure the project themselves."""

from pathlib import Path


def get(path: Path, key: str) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(f"{key}="):
            return line.split("=", 1)[1]
    return ""


def update(path: Path, values: dict[str, str], *, create: bool = False) -> None:
    """Set each key in place; append the ones the file lacks.

    A missing file raises FileNotFoundError unless `create`: only for files holding nothing but derived values.
    """
    if create and not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("# Generated by scripts/deploy_auth.py from the auth stack outputs. Local development only.\n", encoding="utf-8")
    lines = path.read_text(encoding="utf-8").splitlines()
    pending = dict(values)
    for i, line in enumerate(lines):
        key = line.split("=", 1)[0]
        if "=" in line and not line.startswith("#") and key in pending:
            lines[i] = f"{key}={pending.pop(key)}"
    lines += [f"{k}={v}" for k, v in pending.items()]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
