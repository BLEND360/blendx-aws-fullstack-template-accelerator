import contract from "../../../../contract/sse-turns.json";
import { createSseParser } from "./events";
import type { TurnEvent } from "./events";
import { chatReducer, emptyChat } from "../features/chat/chatState";
import type { ChatItem } from "../features/chat/chatState";

// The parser must deliver the fixture's events for the fixture's wire bytes, however they are chunked.
function parse(chunks: string[]): TurnEvent[] {
  const events: TurnEvent[] = [];
  const parser = createSseParser((e) => events.push(e));
  chunks.forEach((c) => parser.push(c));
  parser.end();
  return events;
}

describe.each(contract.turns)("contract turn $name: the parser", ({ wire, events }) => {
  test("delivers the fixture events from the whole wire", () => {
    expect(parse([wire])).toEqual(events);
  });

  test("delivers them when split in two at every position", () => {
    for (let i = 0; i <= wire.length; i++) {
      expect(parse([wire.slice(0, i), wire.slice(i)])).toEqual(events);
    }
  });

  test("delivers them one character at a time", () => {
    expect(parse([...wire])).toEqual(events);
  });

  test("delivers them with \r\n line endings, whole and split in two at every position", () => {
    const crlf = wire.replace(/\n/g, "\r\n");
    expect(parse([crlf])).toEqual(events);
    expect(parse([...crlf])).toEqual(events);
    for (let i = 0; i <= crlf.length; i++) {
      expect(parse([crlf.slice(0, i), crlf.slice(i)])).toEqual(events);
    }
  });
});

// Item ids are generated by the client, so the fixture state has none.
const withoutId = (item: ChatItem): Omit<ChatItem, "id"> => {
  const { id: _id, ...rest } = item as ChatItem & { id?: string };
  return rest;
};

describe.each(contract.turns)("contract turn $name: the reducer", ({ events, state }) => {
  test("reaches the fixture state after the message and the events", () => {
    const sent = chatReducer(emptyChat(), { type: "userSent", id: "u1", text: "hi" });
    const end = events.reduce((s, event) => chatReducer(s, { type: "event", event: event as TurnEvent }), sent);
    expect(end.items[0]).toMatchObject({ kind: "user", text: "hi" });
    expect({ items: end.items.slice(1).map(withoutId), turn: end.turn }).toEqual(state);
  });
});

// Adding a TurnEvent variant fails to compile here until it is listed (and then the vocabulary test fails until the fixture has it).
const HANDLED = {
  delta: true,
  tool_started: true,
  tool_input: true,
  tool_finished: true,
  done: true,
  error: true,
} satisfies Record<TurnEvent["type"], true>;

describe("contract vocabulary closure", () => {
  const vocabulary = [...contract.vocabulary].sort();

  test("the handled event types are exactly the fixture vocabulary", () => {
    expect(Object.keys(HANDLED).sort()).toEqual(vocabulary);
  });

  test("every wire name, taken from a fixture block, produces an event of that type", () => {
    const blocks = contract.turns.flatMap((t) => t.wire.split("\n\n").filter(Boolean));
    for (const name of vocabulary) {
      const block = blocks.find((b) => b.startsWith(`event: ${name}\n`));
      expect(block, `no wire block for ${name}`).toBeDefined();
      expect(parse([`${block}\n\n`]).map((e) => e.type)).toEqual([name]);
    }
  });

  test("every name used on the wire is in the vocabulary", () => {
    const used = contract.turns.flatMap((t) => [...t.wire.matchAll(/^event: (.+)$/gm)].map((m) => m[1]));
    expect([...new Set(used)].sort()).toEqual(vocabulary);
  });
});
